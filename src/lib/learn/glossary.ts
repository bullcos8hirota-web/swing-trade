export const TERM_MAP = new Map(TERMS.map((term) => [term.id, term]))

export function findTerm(id: string): Term | undefined {
  return TERM_MAP.get(id)
}

/** 用語名・読み・説明文をまとめて検索する。 */
export function searchTerms(query: string): Term[] {
  const q = query.trim().toLowerCase()
  if (!q) return TERMS
  return TERMS.filter((term) =>
    [term.term, term.reading ?? '', term.short, ...term.body].some((text) =>
      text.toLowerCase().includes(q),
    ),
  )
}
